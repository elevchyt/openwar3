// Smaller copies of the feature screenshots, so a card ~400 px wide does not decode a 1600×900
// AVIF. AVIF decoding is expensive on an old CPU (a Core 2 Duo laptop scrolled the page in
// stutters, mostly decoding screenshots at four to ten times the pixels it drew), so each
// screenshot wider than a variant gets `<name>@<w>.avif` beside it, and lib/mediaVariants.ts
// lists them for FeatureCard's `srcset`. Run after adding or replacing a file in public/media/:
//   pnpm media
// Encoded 4:4:4 like the originals, so UI text keeps its colour edges. Sharp is Next's own.
import { createRequire } from "node:module";
import { readdirSync, unlinkSync, writeFileSync } from "node:fs";

const require = createRequire(import.meta.url);
const sharp = createRequire(require.resolve("next/package.json"))("sharp");

const DIR = new URL("../public/media/", import.meta.url);
const WIDTHS = [480, 960];
// A variant is only worth having if it is clearly smaller than what it stands in for.
const MIN_RATIO = 1.15;

for (const f of readdirSync(DIR)) if (/@\d+\.avif$/.test(f)) unlinkSync(new URL(f, DIR));

const out = {};
for (const f of readdirSync(DIR).filter((f) => f.endsWith(".avif")).sort()) {
  const src = new URL(f, DIR);
  const { width } = await sharp(src.pathname).metadata();
  const widths = [];
  for (const w of WIDTHS) {
    if (width < w * MIN_RATIO) continue;
    await sharp(src.pathname)
      .resize({ width: w, kernel: "lanczos3" })
      .avif({ quality: 64, chromaSubsampling: "4:4:4", effort: 6 })
      .toFile(new URL(f.replace(/\.avif$/, `@${w}.avif`), DIR).pathname);
    widths.push(w);
  }
  if (widths.length) out[`/media/${f}`] = { width, widths };
}

writeFileSync(
  new URL("../lib/mediaVariants.ts", import.meta.url),
  `// GENERATED by scripts/media-variants.mjs (pnpm media) — do not edit.\n` +
    `// Each screenshot's own width and the smaller copies beside it (<name>@<w>.avif).\n` +
    `export const MEDIA_VARIANTS: Record<string, { width: number; widths: number[] }> = ${JSON.stringify(out, null, 2)};\n`,
);
console.log(out);
