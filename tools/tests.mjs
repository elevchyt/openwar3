// The test manifest: every headless test file, which suite runs it, and whether it needs the
// game data (issue #394).
//
// `sim:test` and `jass:test` used to be one `&&` chain each in package.json, 190 and 43 steps
// long, so the first failure hid every test behind it, and nothing said which tests could run
// without a Warcraft III install. The suites are lists here instead, run by
// tools/run-tests.mjs, which keeps going past a failure and prints a summary at the end.
//
// `data: true` marks a test that needs `Warcraft III/ExtractedData` (`pnpm data:extract`):
// either it stops with "Run `pnpm data:extract` first" (exit 2), or it skips everything it
// checks. Found by running every test in a checkout with no install (2026-11-27): 61 of 231.
// Every other test runs in CI (.github/workflows/ci.yml), so a test marked free that STARTS
// reading the data fails a pull request there, and the fix is to mark it here. A test that only
// skips PART of itself without the data (derived-art, ai-plus-grandprix) stays free: the rest
// of it still runs in CI.
//
// `heap: true` runs the test with --max-old-space-size=8192.
//
// Adding a test: add its file to the right suite below. tools/test-plan-test.mjs fails if a
// `tools/*-test.*` file is named by no suite and no package.json script.

